#!/usr/bin/env node
// Counts what Ground Truth Wiki contains and keeps the numbers in README.md
// honest. The block between <!-- stats --> and <!-- /stats --> is generated.
//
//   node scripts/stats.mjs           print the counts
//   node scripts/stats.mjs --write   update README.md
//   node scripts/stats.mjs --check   fail if README.md is out of date (CI)
import { readJSON, readText, writeText, listFiles, fail } from './lib/fsutil.mjs';
import { loadChapters } from './lib/project.mjs';
import { engineInfo } from './lib/engine-info.mjs';

const chapters = loadChapters();
const books = readJSON('data/books.json');
const engine = engineInfo();
const n = (x) => x.toLocaleString('en-US');

let visuals = 0, interactive = 0;
for (const c of chapters) for (const v of c.meta.visuals) { visuals++; if (engine.interactive.includes(v.split(':')[1])) interactive++; }
const terms = listFiles('data/glossary', '.json').filter((f) => !f.endsWith('/_index.json')).length;
const questions = listFiles('data/quizzes', '.json').filter((f) => !f.endsWith('/_index.json')).reduce((a, f) => a + readJSON(f).length, 0);
const presets = readJSON('data/presets.json').tools;
const s = {
  parts: books.parts.length, books: books.books.length, chapters: chapters.length,
  full: chapters.filter((c) => c.meta.status === 'full').length,
  visuals, interactive, questions, terms,
  events: readJSON('data/timeline.json').events.length,
  paths: readJSON('data/paths.json').paths.length,
  sheets: readJSON('data/cheatsheets.json').sheets.length,
  matrices: readJSON('data/matrices.json').matrices.length,
  playgrounds: presets.filter((t) => t.kind === 'playground').length,
  calculators: presets.filter((t) => t.kind === 'calculator').length,
  wizards: readJSON('data/wizards.json').wizards.length
};

const block = [
  '<!-- stats: generated by npm run stats -- --write; do not edit by hand -->',
  `- **${n(s.chapters)} chapters** in ${s.books} books and ${s.parts} parts, from linear algebra to agent protocols, evals and the frontier`,
  `- **${n(s.visuals)} visuals**, ${n(s.interactive)} of them interactive: steppers, explorers, calculators, sequence players, trees and more`,
  `- **${n(s.questions)} quiz questions** with explanations, plus a boss quiz per book`,
  `- **${n(s.terms)} glossary terms**, linked automatically on first use`,
  `- **${n(s.events)} timeline events**, ${s.paths} learning paths, ${s.sheets} cheat sheets and ${s.matrices} comparison matrices`,
  `- **${s.playgrounds} playgrounds, ${s.calculators} calculators and ${s.wizards} decision wizards**`,
  '<!-- /stats -->'
].join('\n');

const mode = process.argv[2];
if (!mode) { console.log(JSON.stringify(s, null, 2)); process.exit(0); }
const readme = readText('README.md');
const re = /<!-- stats[^>]*-->[\s\S]*?<!-- \/stats -->/;
if (!re.test(readme)) fail('README.md has no <!-- stats --> … <!-- /stats --> block');
const updated = readme.replace(re, block);
if (mode === '--write') { writeText('README.md', updated); console.log('README.md counts updated'); }
else if (mode === '--check') {
  if (updated !== readme) fail('README.md counts are out of date. Run: npm run stats -- --write');
  console.log('README.md counts: up to date');
} else fail('usage: node scripts/stats.mjs [--write|--check]');
