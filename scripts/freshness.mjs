#!/usr/bin/env node
// Lists chapters due for review, as Markdown, so a workflow can post it as an
// issue. Rule 3 of the rulebook: volatile chapters are reviewed after 3
// months, moving after 6, evergreen after 12.
//
//   node scripts/freshness.mjs [--today YYYY-MM-DD] [--soon <months>]
import { fail } from './lib/fsutil.mjs';
import { loadChapters, orderChapters } from './lib/project.mjs';
import { loadSite } from './lib/site.mjs';
import { REVIEW_MONTHS, reviewSchedule, ym } from './lib/freshness.mjs';

const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : fallback; };
const todayArg = opt('--today', null);
const today = todayArg ? new Date(`${todayArg}T00:00:00Z`) : new Date();
if (Number.isNaN(today.getTime())) fail('--today must be a date such as 2027-02-01');
const soon = Number(opt('--soon', 1));


let chapters, site;
try { chapters = orderChapters(loadChapters()); site = loadSite(); } catch (e) { fail(e.message); }

const rows = reviewSchedule(chapters, today).map((r) => ({ c: r.chapter, due: r.due, overdue: r.overdue }));
const dueNow = rows.filter((r) => r.overdue >= 0).sort((a, b) => b.overdue - a.overdue || a.c.meta.book - b.c.meta.book);
const dueSoon = rows.filter((r) => r.overdue < 0 && r.overdue >= -soon).sort((a, b) => a.due - b.due);

const link = (c) => `[${c.meta.order} ${c.meta.title}](${site.repository}/blob/main/${c.file})`;
const table = (list) => ['| Chapter | Stability | Reviewed | Due |', '|---|---|---|---|',
  ...list.map((r) => `| ${link(r.c)} | ${r.c.meta.stability} | ${r.c.meta.reviewed} | ${ym(r.due)} |`)].join('\n');

const out = [`# Freshness report, ${today.toISOString().slice(0, 10)}`, '',
  `Rule 3 of the rulebook: volatile chapters are reviewed every ${REVIEW_MONTHS.volatile} months, moving every ${REVIEW_MONTHS.moving}, evergreen every ${REVIEW_MONTHS.evergreen}. A review checks every dated fact against its source and then sets \`reviewed\` in the frontmatter to the current month.`, ''];
if (!dueNow.length) out.push(`**No chapter is due for review.** All ${chapters.length} chapters are within their schedule.`);
else {
  out.push(`**${dueNow.length} of ${chapters.length} chapters are due for review.**`, '');
  for (const s of ['volatile', 'moving', 'evergreen']) {
    const list = dueNow.filter((r) => r.c.meta.stability === s);
    if (list.length) out.push(`## ${s[0].toUpperCase() + s.slice(1)} (${list.length})`, '', table(list), '');
  }
}
if (dueSoon.length) out.push('', `## Due within ${soon} month${soon === 1 ? '' : 's'} (${dueSoon.length})`, '', table(dueSoon));
const counts = Object.keys(REVIEW_MONTHS).map((s) => `${chapters.filter((c) => c.meta.stability === s).length} ${s}`).join(', ');
out.push('', `Chapters: ${counts}. Generated by \`npm run freshness\`.`);
console.log(out.join('\n').replace(/\n{3,}/g, '\n\n'));
